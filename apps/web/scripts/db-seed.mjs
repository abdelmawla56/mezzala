#!/usr/bin/env node
/**
 * db-seed.mjs
 * Seeds baseline tenants (GCLUB, TEST-000) and seed users per tenant.
 * Uses DATABASE_URL_OWNER — the mz_app role cannot insert into the users table
 * due to DEBT T3 (users are not tenant-members yet).
 *
 * Advisory lock key: 7483921 (stable; derived from 'mz_seed')
 * Produces: seed-accounts.local.md (git-ignored)
 * Called by: npm run db:setup
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import pg from "pg";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const envPath = path.resolve(__dirname, "../.env.local");

// Load .env.local manually
function loadEnv(filePath) {
  if (!existsSync(filePath)) throw new Error(`Missing .env.local at ${filePath}`);
  const lines = readFileSync(filePath, "utf8").split("\n");
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq < 0) continue;
    const key = trimmed.slice(0, eq).trim();
    const val = trimmed.slice(eq + 1).trim();
    if (!process.env[key]) process.env[key] = val;
  }
}

loadEnv(envPath);

if (!process.env.DATABASE_URL_OWNER) {
  console.error("DATABASE_URL_OWNER is not set");
  process.exit(1);
}

const pool = new pg.Pool({
  connectionString: process.env.DATABASE_URL_OWNER,
  max: 2,
});

const ADVISORY_LOCK = 7483921; // 'mz_seed' stable key

const TENANTS = [
  { id: "GCLUB",   name: "Golden Club (dev)" },
  { id: "TEST-000", name: "Test Tenant (CI)" },
];

async function main() {
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    // Advisory lock — prevents double-seed in concurrent runs
    await client.query("SELECT pg_advisory_xact_lock($1)", [ADVISORY_LOCK]);

    // 1. Ensure tenants exist
    for (const t of TENANTS) {
      await client.query(
        `INSERT INTO tenant (id, name) VALUES ($1, $2)
         ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name`,
        [t.id, t.name]
      );
    }
    console.log("Tenants seeded:", TENANTS.map((t) => t.id).join(", "));

    // 2. Seed one admin + one tagger per tenant
    const accounts = [];
    for (const t of TENANTS) {
      const users = [
        { email: `admin@${t.id.toLowerCase().replace(/[^a-z0-9]/g, "")}.dev`, role: "admin" },
        { email: `tagger@${t.id.toLowerCase().replace(/[^a-z0-9]/g, "")}.dev`, role: "tagger" },
      ];
      for (const u of users) {
        const result = await client.query(
          `INSERT INTO users (email, role, club_id)
           VALUES ($1, $2, $3)
           ON CONFLICT (email) DO UPDATE SET role = EXCLUDED.role, club_id = EXCLUDED.club_id
           RETURNING id`,
          [u.email, u.role, t.id]
        );
        const userId = result.rows[0].id;
        accounts.push({ clubId: t.id, email: u.email, role: u.role, authMethod: "magic-link", userId });
      }
    }

    await client.query("COMMIT");

    // 3. Write seed-accounts.local.md (git-ignored)
    const mdPath = path.resolve(__dirname, "../../../seed-accounts.local.md");
    const md = [
      "# Seed Accounts (LOCAL DEV — DO NOT COMMIT)",
      "",
      "> Generated by db-seed.mjs. Git-ignored. Magic-link authenticated.",
      "",
      ...accounts.map(
        (a) =>
          `## ${a.email}\n- Club: \`${a.clubId}\`\n- Role: \`${a.role}\`\n- Auth: \`${a.authMethod}\`\n- User ID: ${a.userId}\n`
      ),
    ].join("\n");
    writeFileSync(mdPath, md, "utf8");
    console.log("seed-accounts.local.md written to", mdPath);
    console.log("Seeded accounts:", accounts.map((a) => a.email).join(", "));
  } catch (err) {
    await client.query("ROLLBACK").catch(() => {});
    console.error("db-seed failed:", err.message);
    process.exit(1);
  } finally {
    client.release();
    await pool.end();
  }
}

main();
